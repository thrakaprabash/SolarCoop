const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const {spawnSync}=require('node:child_process');
const {createClient}=require('@supabase/supabase-js');
const {projectRef,requireLinkedProject}=require('./database.cjs');
const root=path.resolve(__dirname,'..');
const households=require('../database/demo-households.json');
const batch='solarcoop-households-20261008';
const credentialsFile=path.join(root,'database','demo-credentials.local.json');
const reportFile=path.join(root,'docs','DEMO_ACCOUNTS.local.md');
const emailFor=h=>`${h.key}@demo.solarcoop.test`;

function adminKey(ref) {
  // Capture the CLI output in memory. Never print or save the project's API keys.
  const result=spawnSync(process.execPath,[path.join(root,'node_modules','supabase','dist','supabase.js'),
    'projects','api-keys','--project-ref',ref,'--reveal','--output','json'],{cwd:root,encoding:'utf8',windowsHide:true});
  if(result.status!==0)throw Error('Cannot obtain server-side access. Run npm run db:login with an account that owns this project.');
  const payload=JSON.parse(result.stdout);
  const keys=Array.isArray(payload)?payload:payload.api_keys;
  const key=keys?.find(k=>k.name==='service_role') || keys?.find(k=>k.type==='secret');
  if(!key?.api_key)throw Error('No server-side admin key available for this project.');
  return key.api_key;
}
function checked(result,description) {
  if(result.error)throw Error(`${description}: ${result.error.message}`);
  return result.data;
}
function saveCredentials(credentials) {
  fs.writeFileSync(credentialsFile,JSON.stringify(credentials,null,2)+'\n',{mode:0o600});
}
function writeReport(credentials,rows,counts) {
  const lines=['# SolarCoop demo accounts','',`Seeded project: \`${credentials.projectRef}\`. Verified: ${new Date().toISOString()}.`,
    '',`Total community: **${counts.owner || 0} solar owners and ${counts.consumer || 0} consumers**. This batch adds five owners and eight consumers.`,
    '', 'These are fictional demonstration accounts. Emails are test addresses, already confirmed; no email verification step is needed. All listed accounts are active. Passwords belong only in this local file; it is excluded from Git.',
    '', '## Logins','', '| Role | Name | Email | Password | Household |','|---|---|---|---|---|'];
  for(const h of households)lines.push(`| ${h.role} | ${h.name} | ${emailFor(h)} | ${credentials.accounts[h.key].password} | ${h.household} |`);
  lines.push('', '## Solar systems','', 'Panels are modelled as 400 W each. Battery capacity is in kWh; charge is a starting percentage and changes during simulation. Inverter serials identify virtual devices, not physical equipment.',
    '', '| Owner | Inverter serial | Solar kW | Panels | Strings | Battery kWh | Initial charge | Load profile × factor | Scenario |', '|---|---|---|---|---|---|---|---|---|');
  for(const h of households.filter(h=>h.role==='owner')) {
    const row=rows.find(r=>r.key===h.key);
    lines.push(`| ${h.name} | ${row.serial} | ${h.capacity} | ${h.panels} | ${h.strings} | ${h.battery} | ${h.battery ? `${h.soc}%` : 'No battery'} | ${h.load} × ${h.factor} | ${h.scenario} |`);
  }
  lines.push('', '## Consumers','', 'Consumers have virtual meters, zero solar panels, zero solar capacity, and no batteries.',
    '', '| Consumer | Meter serial | Load profile × factor | Expected daily consumption kWh | Scenario |', '|---|---|---|---|---|');
  for(const h of households.filter(h=>h.role==='consumer')) {
    const base={small:12.1,family:20.2,large:30,business:37.6}[h.load];
    lines.push(`| ${h.name} | ${rows.find(r=>r.key===h.key).serial} | ${h.load} × ${h.factor} | ~${(base*h.factor).toFixed(1)} | ${h.scenario} |`);
  }
  lines.push('', '## Run the demo','', '1. Run `npm start -- --go --lan` and open the app in Expo Go.',
    '2. Open `http://localhost:5050/` to control the simulator. Use the normal URL for database-backed readings.',
    '3. Log in using one of the accounts above. Owners see generation, consumption, surplus, and battery readings. Consumers generate consumption only.',
    '4. Change weather or simulation time to vary production. Evening time increases household demand; business profiles peak during working hours.',
    '5. Inject a fault into an owner inverter to demonstrate the owner notification and technician diagnostics/health workflow. Clear it or complete its repair afterward.',
    '', 'Energy readings are generated by the existing simulator and saved into the app database. Daily figures depend on simulation time, weather and run duration; expected consumption above is a full simulated 24-hour estimate before random variation. No fabricated trading/payment transactions are inserted.',
    '', 'The scenario locations describe fictional households; they are not geocoded addresses. Distance labels are demo estimates. Existing accounts and passwords were preserved and are not listed here because their passwords cannot be read from Supabase.',
    '', '## Repeat safely','', '`node scripts/seed-demo-households.cjs` previews the batch. Add `--apply` to create missing accounts. A repeat verifies this batch and does not reset passwords, batteries, customised devices, faults or existing readings.',
    '', 'Provisioning uses the [Supabase Auth Admin API](https://supabase.com/docs/reference/javascript/auth-admin-createuser). Server-side keys are held only in the script process and never copied into the app or this document.','');
  fs.writeFileSync(reportFile,lines.join('\n'),{mode:0o600});
}
async function main() {
  process.loadEnvFile(path.join(root,'.env'));
  const ref=projectRef();requireLinkedProject(ref);
  const admin=createClient(process.env.EXPO_PUBLIC_SUPABASE_URL,adminKey(ref),{auth:{persistSession:false,autoRefreshToken:false}});
  const users=[];
  for(let page=1;;page++) {
    const data=checked(await admin.auth.admin.listUsers({page,perPage:1000}),'List users');
    users.push(...data.users);if(data.users.length<1000)break;
  }
  const profiles=checked(await admin.from('profiles').select('id,role,status,household_id'),'Read profiles');
  const counts=profiles.reduce((acc,p)=>(acc[p.role]=(acc[p.role]||0)+1,acc),{});
  console.log(`Project ${ref}: ${counts.owner||0} owners, ${counts.consumer||0} consumers before this run.`);
  if(process.argv.includes('--verify-feed')) {
    const ids=households.map(h=>users.find(u=>u.email===emailFor(h))?.id);
    if(ids.some(id=>!id))throw Error('Some demo accounts have not been created yet.');
    const metrics=checked(await admin.from('energy_metrics').select('user_id,instant_production,instant_consumption,battery_capacity,is_simulated,updated_at').in('user_id',ids),'Read live metrics');
    const devices=checked(await admin.from('sim_devices').select('household_user_id,capacity_kw,panel_count,string_count,battery_kwh,load_profile,load_factor').in('household_user_id',ids),'Read live devices');
    for(const h of households) {
      const id=users.find(u=>u.email===emailFor(h)).id;
      const m=metrics.find(m=>m.user_id===id), d=devices.find(d=>d.household_user_id===id);
      if(!m?.is_simulated || Date.now()-Date.parse(m.updated_at)>60000)throw Error(`No fresh simulated reading for ${h.key}. Run the simulator and retry.`);
      if(!d || Number(d.capacity_kw)!==h.capacity || d.panel_count!==h.panels || d.string_count!==h.strings || Number(d.battery_kwh)!==h.battery || d.load_profile!==h.load || Number(d.load_factor)!==h.factor)throw Error(`Device configuration differs from the batch for ${h.key}.`);
      if(Number(m.battery_capacity)!==h.battery || (h.role==='consumer' && Number(m.instant_production)!==0) || Number(m.instant_consumption)<=0)throw Error(`Reading does not match hardware/load for ${h.key}.`);
    }
    console.log(`Verified ${metrics.length} fresh database feeds: correct solar, panels, strings, battery capacity and household loads. Consumer generation is zero.`);
    return;
  }
  for(const h of households) {
    const user=users.find(u=>u.email===emailFor(h));
    if(user && user.app_metadata?.demo_batch!==batch)throw Error(`Email collision for ${h.key}; refusing to change an unrelated account.`);
    const profile=profiles.find(p=>p.household_id===h.household);
    if(profile && profile.id!==user?.id)throw Error(`Household collision for ${h.household}.`);
    console.log(`${user?'Verify':'Create'} ${h.role}: ${h.name} (${h.capacity} kW, ${h.panels} panels, ${h.battery} kWh battery, ${h.load} × ${h.factor}).`);
  }
  if(!process.argv.includes('--apply')) {console.log('Preview only. Add --apply to seed this project.');return;}
  let credentials=fs.existsSync(credentialsFile)?JSON.parse(fs.readFileSync(credentialsFile,'utf8')):{projectRef:ref,accounts:{}};
  if(credentials.projectRef!==ref)throw Error('Local demo credentials belong to another project.');
  for(const h of households) {
    const user=users.find(u=>u.email===emailFor(h));
    if(user && !credentials.accounts[h.key])throw Error(`Local password missing for ${h.key}; refusing to reset it.`);
    if(!credentials.accounts[h.key])credentials.accounts[h.key]={password:`Sc!${crypto.randomBytes(9).toString('base64url')}9a`};
  }
  saveCredentials(credentials);
  const rows=[];
  for(const h of households) {
    let user=users.find(u=>u.email===emailFor(h));
    if(!user) {
      user=checked(await admin.auth.admin.createUser({email:emailFor(h),password:credentials.accounts[h.key].password,email_confirm:true,
        app_metadata:{demo_batch:batch},user_metadata:{name:h.name,role:h.role,household_id:h.household,solar_capacity_kw:h.capacity}}),`Create ${h.key}`).user;
      credentials.accounts[h.key].id=user.id;saveCredentials(credentials);
    }
    if(!credentials.accounts[h.key].configured) {
      const profile=checked(await admin.from('profiles').select('id,role,status,household_id').eq('id',user.id).single(),`Verify profile ${h.key}`);
      if(profile.role!==h.role || profile.household_id!==h.household || profile.status!=='active')throw Error(`Unexpected profile for ${h.key}.`);
      checked(await admin.from('profiles').update({distance_label:h.distance,battery_soc:h.soc}).eq('id',user.id),`Configure profile ${h.key}`);
      checked(await admin.from('sim_devices').update({inverter_serial:`SC-${h.role==='owner'?'INV':'MTR'}-${h.household}`,
        capacity_kw:h.capacity,panel_count:h.panels,string_count:h.strings,panel_health:Array(h.panels).fill(1),
        load_profile:h.load,load_factor:h.factor,battery_kwh:h.battery,battery_level:h.soc}).eq('household_user_id',user.id).select('id').single(),`Configure device ${h.key}`);
      credentials.accounts[h.key].configured=true;saveCredentials(credentials);
    }
    const device=checked(await admin.from('sim_devices').select('id,inverter_serial,capacity_kw,panel_count,battery_kwh').eq('household_user_id',user.id).single(),`Read device ${h.key}`);
    const client=createClient(process.env.EXPO_PUBLIC_SUPABASE_URL,process.env.EXPO_PUBLIC_SUPABASE_ANON_KEY,{auth:{persistSession:false,autoRefreshToken:false}});
    const login=checked(await client.auth.signInWithPassword({email:emailFor(h),password:credentials.accounts[h.key].password}),`Login ${h.key}`);
    if(login.user.id!==user.id)throw Error(`Unexpected login identity for ${h.key}.`);
    const ownProfile=checked(await client.from('profiles').select('role,status').eq('id',user.id).single(),`Read own profile ${h.key}`);
    if(ownProfile.role!==h.role || ownProfile.status!=='active')throw Error(`Incorrect role access for ${h.key}.`);
    await client.auth.signOut();rows.push({key:h.key,serial:device.inverter_serial});
    console.log(`Verified login + active ${h.role} profile + virtual device: ${h.key}.`);
  }
  const finalProfiles=checked(await admin.from('profiles').select('role'),'Count profiles');
  const finalCounts=finalProfiles.reduce((acc,p)=>(acc[p.role]=(acc[p.role]||0)+1,acc),{});
  writeReport(credentials,rows,finalCounts);
  console.log(`Complete: ${finalCounts.owner} owners and ${finalCounts.consumer} consumers. Credentials: docs/DEMO_ACCOUNTS.local.md`);
}
if(require.main===module)main().catch(error=>{console.error(error.message);process.exitCode=1;});
